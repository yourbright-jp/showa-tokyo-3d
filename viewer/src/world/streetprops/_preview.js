// Development-only turntable for street props (not part of the world build). Renders every prop
// type in a row on a flat ground so details can be inspected quickly.
import * as THREE from 'three';
import { applyLook, makeComposer, focusShadow } from '../../core/look.js';
import { makeRng } from '../../core/rng.js';
import { Batch, mat4, mul } from './kit.js';
import { makeMaterials, makeAtlas } from './materials.js';
import { buildBicycle, buildMotorbike, buildSedan, buildVan, buildTruck } from './vehicles.js';
import * as C from './clutter.js';
import { buildStreetLamp } from './lamps.js';
import { buildUtilityPole } from './poles.js';

const q = new URLSearchParams(location.search);
const w = Number(q.get('w') || 960), h = Number(q.get('h') || 540);
const renderer = new THREE.WebGLRenderer({ antialias: false, preserveDrawingBuffer: true });
renderer.setSize(w, h, false); renderer.shadowMap.enabled = true; renderer.shadowMap.type = THREE.PCFSoftShadowMap;
renderer.outputColorSpace = THREE.SRGBColorSpace;
document.body.appendChild(renderer.domElement);
const scene = new THREE.Scene();
const camera = new THREE.PerspectiveCamera(Number(q.get('fov') || 35), w / h, 0.05, 2000);
const ctx = { THREE, scene, renderer, camera, rng: makeRng(1976), quality: { shadowMap: 2048, msaa: 4 }, tag() {}, log: console.log };
applyLook(ctx, q.get('look') || 'clear-afternoon');
const ground = new THREE.Mesh(new THREE.PlaneGeometry(200, 200), new THREE.MeshStandardMaterial({ color: 0x6f6a62, roughness: 0.95 }));
ground.rotation.x = -Math.PI / 2; ground.receiveShadow = true; scene.add(ground);
const wall = new THREE.Mesh(new THREE.BoxGeometry(200, 8, 0.3), new THREE.MeshStandardMaterial({ color: 0xb9b2a4, roughness: 0.9 }));
wall.position.set(0, 4, -1.6); wall.receiveShadow = true; wall.castShadow = true; scene.add(wall);
const atlas = makeAtlas(ctx);
const mats = makeMaterials(ctx, atlas);
const kit = { B: new Batch(), BS: new Batch(), BA: new Batch({ uv: true }), BF: new Batch(), BG: new Batch(), BW: new Batch() };
const R = (k) => ctx.rng(`preview/${k}`);
let x = 0;
const at = (dx, ry = 0) => { const m = mat4(x, 0, 0, ry); x += dx; return m; };
buildBicycle(kit.B, kit.BA, at(1.0, 0.3), R('b1'), { stepThrough: true, basket: true, carrier: true });
buildBicycle(kit.B, kit.BA, at(1.0, -0.2), R('b2'), { stepThrough: false, basket: false, carrier: true });
buildMotorbike(kit.B, at(1.4, 0.4), R('m1'), { box: true });
buildMotorbike(kit.B, at(1.6, -0.3), R('m2'), { box: false });
C.buildVending(kit, at(1.0), R('v1'), 'cig');
C.buildVending(kit, at(1.0), R('v2'), 'drinkRed');
C.buildVending(kit, at(1.2), R('v3'), 'drinkBlue');
C.buildPhoneBooth(kit, at(1.3), R('pb'));
C.buildPostbox(kit, at(0.8), R('post'));
for (const t of ['concreteBox', 'concreteCyl', 'poly', 'dustbin']) C.buildBin(kit, at(0.75), R(t), t);
C.buildCrateStack(kit, at(1.2), R('cr'), 2);
C.buildPlants(kit, at(1.6), R('pl'), 3);
C.buildPlants(kit, at(1.6), R('pl2'), 3);
C.buildCardboard(kit, at(0.9), R('cb'));
C.buildGasCylinders(kit, at(0.9), R('gas'));
C.buildWoodCrates(kit, at(0.8), R('wc'));
C.buildStool(kit, at(0.6), R('st')); C.buildBucket(kit, at(0.5), R('bu')); C.buildBroom(kit, at(0.5), R('br')); C.buildAshtray(kit, at(0.6), R('as')); C.buildIceBox(kit, at(0.9), R('ib'));
buildStreetLamp(kit.B, { x: x + 1, z: 0.8, gy: 0, ry: 0, rng: R('lamp'), flowers: true }); x += 2.4;
buildUtilityPole(kit.B, kit.BA, { x: x, z: -0.9, gy: 0, ry: 0, H: 11, rng: R('pole'), wireBatch: kit.BW, hv: [1.2, 1.7, 2.2], lv: [1.0, 1.45, 1.9], rack: true, tel: 0.95, transformer: 1, lamp: true, ad: 'poleAdA' }); x += 2;
buildSedan(kit.B, kit.BA, mat4(x + 2.5, 0, 1.5, 0.5), R('car1'), {}); 
buildSedan(kit.B, kit.BA, mat4(x + 7.5, 0, 1.5, -0.4), R('car2'), { taxi: true });
buildVan(kit.B, kit.BA, mat4(x + 12.5, 0, 1.5, 0.3), R('van'));
buildTruck(kit.B, kit.BA, mat4(x + 17.5, 0, 1.5, -0.3), R('truck'));
const add = (b, m, cast) => { if (b.triCount) { const mesh = b.toMesh(m); mesh.castShadow = cast; mesh.receiveShadow = true; scene.add(mesh); } };
add(kit.B, mats.opaque, true); add(kit.BS, mats.opaque, false); add(kit.BA, mats.atlas, true); add(kit.BF, mats.foliage, true); add(kit.BW, mats.opaque, false);
if (kit.BG.triCount) scene.add(kit.BG.toMesh(mats.glass));
const cam = (q.get('cam') || '4,1.6,6').split(',').map(Number), tgt = (q.get('tgt') || '4,0.8,0').split(',').map(Number);
camera.position.set(...cam); camera.lookAt(...tgt);
focusShadow(ctx, camera, 25);
const composer = makeComposer(ctx, camera, w, h);
composer.render(); composer.render();
window.__renderDone = true;
